export const vocabulary = wordGroups.map(({ id, title, words }) => ({
  id,
  title,
  lessons: words.map((word): ChoiceLesson => ({
    id: word.id,
    title: word.kana,
    japanese: word.spelling,
    english: word.meaning,
    explanation: word.note ?? "",
    prompt: "What does this word mean?",
    stem: word.kana,
    choices: words.map((entry) => entry.meaning),
    answer: word.meaning,
    feedback: `${word.spelling} (${word.kana}) means ${word.meaning}.`,
    audio: word.audio,
  })),
}));

export const vocabularyRecall = wordGroups.map(({ title, words }) => ({
  title,
  lessons: words.map((word): ChoiceLesson => ({
    id: word.id,
    title: word.meaning,
    japanese: "",
    english: "",
    explanation: "",
    prompt: "Type the Japanese word in kana or kanji.",
    stem: "",
    choices: [],
    acceptedAnswers: [
      word.kana,
      word.spelling,
      ...(word.id === "friend" ? ["友達"] : []),
    ],
    answer: word.kana,
    feedback: `${word.spelling} (${word.kana}) means ${word.meaning}.`,
  })),
}));
